// Bundle skills/<name>/SKILL.md and prompts/<name>.md into
// api/prompts/skills.gen.ts so the Worker serves them as MCP prompts.
// Runs before dev/build/deploy; add a file, rebuild, it shows up in chat.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
type Doc = { name: string; title: string; description: string; body: string };

function parse(name: string, raw: string): Doc {
	const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(raw);
	const meta: Record<string, string> = {};
	for (const line of (m?.[1] ?? "").split("\n")) {
		const kv = /^(\w+):\s*(.*)$/.exec(line);
		if (kv) meta[kv[1]] = kv[2].replace(/^["']|["']$/g, "").trim();
	}
	return {
		name: (meta.name ?? name).replace(/[^\w-]/g, "_"),
		title: meta.title ?? meta.name ?? name,
		description: meta.description ?? "",
		body: (m ? m[2] : raw).trim(),
	};
}

const docs: Doc[] = [];
const sk = join(root, "skills");
if (existsSync(sk))
	for (const d of readdirSync(sk, { withFileTypes: true }))
		if (d.isDirectory() && existsSync(join(sk, d.name, "SKILL.md")))
			docs.push(
				parse(d.name, readFileSync(join(sk, d.name, "SKILL.md"), "utf8")),
			);
const pr = join(root, "prompts");
if (existsSync(pr))
	for (const f of readdirSync(pr))
		if (f.endsWith(".md") && f !== "README.md")
			docs.push(parse(f.slice(0, -3), readFileSync(join(pr, f), "utf8")));

docs.sort((a, b) => a.name.localeCompare(b.name));
writeFileSync(
	join(root, "api/prompts/skills.gen.ts"),
	`// Generated by scripts/gen-skills.ts. Edit skills/ and prompts/, not this file.\nexport const repoPrompts = ${JSON.stringify(docs, null, "\t")};\n`,
);
console.log(`gen-skills: ${docs.length} prompt(s)`);
