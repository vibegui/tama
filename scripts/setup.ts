// One-command deploy of this tama to YOUR Cloudflare account.
//
//   bun run setup -- --owner you@example.com [--slug beto] [--dry-run]
//
// Creates (or reuses) the D1 database and R2 bucket, writes wrangler.toml,
// generates VAPID keys, stores secrets, applies migrations, builds and deploys.
// Prints the MCP URL to connect in deco chat (chat.decocms.com).
//
// Secrets never hit stdout or disk: VAPID keys are generated in-process and
// piped into `wrangler secret put`; ANTHROPIC_API_KEY / OPENAI_API_KEY /
// PERPLEXITY_API_KEY are forwarded from your shell env only if set.
// Safe to re-run: existing D1/R2 are reused; VAPID keys are kept unless
// --new-vapid is passed (rotating them breaks existing push subscriptions).

import { existsSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const argv = process.argv.slice(2);
const flag = (n: string) => argv.includes(`--${n}`);
const opt = (n: string) => {
	const i = argv.indexOf(`--${n}`);
	return i >= 0 ? argv[i + 1] : undefined;
};
const dry = flag("dry-run");

const pet = JSON.parse(readFileSync(join(root, "config/pet.json"), "utf8"));
const slug = (opt("slug") ?? pet.name ?? "tama")
	.toLowerCase()
	.normalize("NFD")
	.replace(/[̀-ͯ]/g, "")
	.replace(/[^a-z0-9]+/g, "-")
	.replace(/^-|-$/g, "");
const owner = opt("owner")?.trim().toLowerCase();
const name = `tama-${slug}`;
const dbName = name;
const bucket = `${name}-files`;

function run(cmd: string[], input?: string): string {
	if (dry) {
		console.log(`  $ ${cmd.join(" ")}${input ? " < (secret)" : ""}`);
		return "";
	}
	const p = Bun.spawnSync(cmd, {
		cwd: root,
		stdin: input ? new TextEncoder().encode(input) : "inherit",
		stdout: "pipe",
		stderr: "pipe",
	});
	const out = p.stdout.toString() + p.stderr.toString();
	if (p.exitCode !== 0) throw new Error(`${cmd.join(" ")} failed:\n${out}`);
	return out;
}
const wr = (...a: string[]) => ["bunx", "wrangler", ...a];

async function vapid() {
	const b64u = (b: ArrayBuffer) => Buffer.from(b).toString("base64url");
	const { publicKey, privateKey } = (await crypto.subtle.generateKey(
		{ name: "ECDSA", namedCurve: "P-256" },
		true,
		["sign", "verify"],
	)) as CryptoKeyPair;
	const jwk = (await crypto.subtle.exportKey("jwk", privateKey)) as JsonWebKey;
	return {
		VAPID_PUBLIC_KEY: b64u(await crypto.subtle.exportKey("raw", publicKey)),
		VAPID_PRIVATE_KEY: jwk.d as string,
	};
}

async function main() {
	if (!owner?.includes("@"))
		throw new Error("pass --owner <your deco chat email>");
	console.log(`tama setup: ${name} (owner ${owner})${dry ? " [dry run]" : ""}`);

	// 1. Account
	const who = dry ? "" : run(wr("whoami"));
	const account = /\b([0-9a-f]{32})\b/.exec(who)?.[1];
	if (!dry && !account)
		throw new Error("not logged in to Cloudflare: run `bunx wrangler login`");

	// 2. D1 (reuse if it exists)
	let dbId = "";
	if (!dry) {
		const list = JSON.parse(run(wr("d1", "list", "--json")) || "[]") as {
			name: string;
			uuid: string;
		}[];
		dbId = list.find((d) => d.name === dbName)?.uuid ?? "";
	}
	if (!dbId) {
		const out = run(wr("d1", "create", dbName));
		dbId = /"?database_id"?\s*[:=]\s*"([0-9a-f-]{36})"/.exec(out)?.[1] ?? "";
		if (!dry && !dbId) throw new Error(`could not read database_id:\n${out}`);
	}

	// 3. R2 (create is idempotent enough: ignore "already exists")
	try {
		run(wr("r2", "bucket", "create", bucket));
	} catch (e) {
		if (!String(e).includes("already exists")) throw e;
	}

	// 4. wrangler.toml (back up a different existing config)
	const path = join(root, "wrangler.toml");
	if (
		existsSync(path) &&
		!readFileSync(path, "utf8").includes(`name = "${name}"`)
	) {
		console.log(
			"  wrangler.toml exists for another deploy: saved as wrangler.toml.bak",
		);
		if (!dry) renameSync(path, `${path}.bak`);
	}
	const toml = `# Generated by scripts/setup.ts. Re-run setup instead of editing by hand.
name = "${name}"
main = "api/main.cf.ts"
compatibility_date = "2026-05-01"
compatibility_flags = ["nodejs_compat"]

[vars]
AI_GATEWAY_ACCOUNT_ID = "${account ?? "<account>"}"
AI_GATEWAY_NAME = "default"
VIBEBOOK_OWNERS = "${owner}"
VAPID_SUBJECT = "mailto:${owner}"

[[d1_databases]]
binding = "DB"
database_name = "${dbName}"
database_id = "${dbId || "<created>"}"
migrations_dir = "api/db/migrations"

[[r2_buckets]]
binding = "FILES"
bucket_name = "${bucket}"

[ai]
binding = "AI"

[assets]
directory = "dist/client"
binding = "ASSETS"

[triggers]
crons = ["*/2 * * * *"]
`;
	if (dry)
		console.log(
			`  write wrangler.toml (${name}, db ${dbName}, bucket ${bucket})`,
		);
	else writeFileSync(path, toml);

	// 5. Secrets
	const existing = dry ? "" : run(wr("secret", "list"));
	if (flag("new-vapid") || !existing.includes("VAPID_PRIVATE_KEY")) {
		for (const [k, v] of Object.entries(await vapid()))
			run(wr("secret", "put", k), v);
	}
	for (const k of [
		"ANTHROPIC_API_KEY",
		"OPENAI_API_KEY",
		"PERPLEXITY_API_KEY",
	]) {
		const v = process.env[k];
		if (v) {
			run(wr("secret", "put", k), v);
			console.log(`  ${k} stored (${v.length} chars)`);
		}
	}
	if (!process.env.ANTHROPIC_API_KEY && !existing.includes("ANTHROPIC_API_KEY"))
		console.log(
			"  note: no ANTHROPIC_API_KEY. Exam/prescription extraction stays off until you run\n" +
				"        bunx wrangler secret put ANTHROPIC_API_KEY",
		);

	// 6. Migrate, build, deploy
	run(wr("d1", "migrations", "apply", "DB", "--remote"));
	run(["bun", "run", "build"]);
	const out = run(wr("deploy"));
	const url =
		/https:\/\/[^\s]+\.workers\.dev/.exec(out)?.[0] ??
		`https://${name}.<you>.workers.dev`;

	console.log(`
Deployed: ${url}
Connect it in deco chat (chat.decocms.com) as an MCP: ${url}/api/mcp
Only ${owner} gets in (VIBEBOOK_OWNERS in wrangler.toml).`);
}

main().catch((e) => {
	console.error(String(e.message ?? e));
	process.exit(1);
});
